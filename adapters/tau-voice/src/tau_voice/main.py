"""tau-voice converter: tau2 voice tasks -> harbor-voice task directories.

Run once, locally::

    tau-voice --tau2-root ../tau2-bench --output-dir datasets/tau-voice

Each task directory is a harbor task; harbor's environment layer runs it::

    <domain>-<slug>-<hash>/
    ├── task.toml                   harbor's task config, for harbor's runner
    ├── instruction.md              carries voice.toml for the call runner
    ├── voice.toml                  [call] driver, [environment], [verifier]
    ├── environment/
    │   ├── Dockerfile              main: where harbor-voice runs the call
    │   ├── docker-compose.yaml     adds the tau2 service next to main
    │   └── sidecar/                tau2's image: server, evaluator
    └── tests/test.sh               the verifier, in main; grades via tau2

Run one with ``harbor-voice trials start -p <task> -m <s2s spec>``, or a
dataset with ``harbor-voice jobs start`` (``job-config`` writes the config).

By default both images are built from the task, as harbor tasks are (tau3-bench
builds its runtime the same way) — each trial's ``compose build`` is a cache
hit after the first. ``--prebuilt`` instead names images made once by
``tau-voice build-image`` (:mod:`tau_voice.images`), so a trial makes no
registry or PyPI call before its call starts — frontier-cs's pattern, for
flaky networks and for runs that must not rebuild.

The agent under test is not in the task: the run picks it, as a harbor job
does (``-m openai.realtime/gpt-realtime-1.5``).

Task ids are read from tau2's own ``split_tasks.json`` (``base`` is the split
tau-voice evaluates: airline 50, retail 114, telecom 114), so tau2 need not be
importable here.
"""

from __future__ import annotations

import argparse
import random
import hashlib
import json
import re
import shutil
from pathlib import Path

from tau_voice import images

DOMAINS = ("airline", "retail", "telecom")
REVIEW_MODEL = "bedrock/us.anthropic.claude-opus-4-5-20251101-v1:0"
PARITY_TASKS = Path(__file__).resolve().parents[2] / "parity_tasks.json"
TEMPLATE = Path(__file__).resolve().parents[2] / "template"

# Names only, as ${VAR} templates resolved from the host at run time; values
# are never written into a task directory.
SIDECAR_ENV = (
    "OPENAI_API_KEY",
    "AWS_ACCESS_KEY_ID",
    "AWS_SECRET_ACCESS_KEY",
    "AWS_REGION",
    "TAU2_VOICE_ID_MATT_DELANEY",
    "TAU2_VOICE_ID_LISA_BRENNER",
)
MAIN_ENV = ("OPENAI_API_KEY", "ELEVENLABS_API_KEY")
"""main runs the call: the agent under test (the reference agent is OpenAI
Realtime) and the caller's TTS."""


def task_env() -> str:
    """``[environment].env``: every variable main or the compose file uses.

    On a remote backend (Daytona, EC2, ...) harbor runs ``docker compose``
    with the task's env and its own infra vars only — not this machine's
    environment — so a variable the compose file passes to the sidecar must
    be declared here to reach it. Harbor fills each ``${VAR}`` from the
    orchestrator's environment at trial start.
    """
    names = dict.fromkeys((*MAIN_ENV, *SIDECAR_ENV))
    pairs = [f'{name} = "${{{name}}}"' for name in names]
    pairs.append(
        f'TAU_VOICE_REVIEW_MODEL = "${{TAU_VOICE_REVIEW_MODEL:-{REVIEW_MODEL}}}"'
    )
    pairs.append('HARBOR_VOICE_TTS_CACHE = "/cache/tts"')
    return "{ " + ", ".join(pairs) + " }"


COMPOSE = """\
# Generated by tau_voice.main. Harbor supplies main; this adds the tau2
# service: tools, prompts, the caller's LLM, grading.
services:
  main:
    depends_on:
      tau2:
        condition: service_healthy
    volumes:
      # Caller audio and wheels' dependencies survive across trials.
      - ${{HARBOR_VOICE_CACHE_DIR:-${{HOME}}/.cache/harbor-voice}}/tts:/cache/tts
      - ${{HARBOR_VOICE_CACHE_DIR:-${{HOME}}/.cache/harbor-voice}}/uv:/root/.cache/uv
  tau2:
{tau2_source}
    environment:
{env}
      - AWS_REGION_NAME=${{AWS_REGION}}
      - TAU_VOICE_REVIEW_MODEL=${{TAU_VOICE_REVIEW_MODEL:-{review}}}
"""


RESOURCES = """\
cpus = 2
memory_mb = 4096
storage_mb = 10240"""
"""What one trial needs, for backends that size a sandbox from the task
(Daytona, Modal, ...): the tau2 image alone is ~3.5 GB on disk."""


TAU2_RUN_SEED = 300
"""tau2's ``--seed`` default."""


def trial_seeds(run_seed: int = TAU2_RUN_SEED, trials: int = 1) -> list[int]:
    """The per-trial seeds tau2 derives from its run seed (``runner/batch.py``).

    Every task in trial k gets ``seeds[k]``, and that seed reaches the caller's
    LLM requests, so parity needs the same numbers on both sides. For the
    default run seed 300 they are 626729, 373753, 361454, ...
    """
    rng = random.Random(run_seed)
    return [rng.randint(0, 1_000_000) for _ in range(trials)]


def task_dir_name(domain: str, task_id: str) -> str:
    """Readable and collision-free: telecom ids share long prefixes."""
    slug = re.sub(r"[^a-z0-9]+", "-", task_id.lower()).strip("-")[:48].strip("-")
    digest = hashlib.sha1(f"{domain}/{task_id}".encode()).hexdigest()[:8]
    return f"{domain}-{slug}-{digest}"


def voice_toml(
    domain: str, task_id: str, *, complexity: str, seed: int, prebuilt: bool = False
) -> str:
    main_image = (
        f"docker_image = {json.dumps(images.main_image())}\n" if prebuilt else ""
    )
    return f"""\
# Generated by tau_voice.main from tau2-bench@2174a60.
task = {json.dumps(f"tau-voice/{domain}/{task_id}")}
seed = {seed}

[call]
driver = "tau_voice.trial:drive"
timeout_sec = 3600

[call.config]
domain = {json.dumps(domain)}
task_id = {json.dumps(task_id)}
speech_complexity = {json.dumps(complexity)}
seed = {seed}
hallucination_retries = 3

[environment]
{main_image}build_timeout_sec = 1800
{RESOURCES}
env = {task_env()}

[verifier]
timeout_sec = 900
"""


def task_toml(name: str, domain: str, task_id: str, *, prebuilt: bool) -> str:
    """Harbor's ``task.toml``: the same task, for harbor's job runner."""
    main_image = (
        f"docker_image = {json.dumps(images.main_image())}\n" if prebuilt else ""
    )
    return f"""\
# Generated by tau_voice.main from tau2-bench@2174a60. Run with harbor's job
# runner: harbor-voice trials start -p <task> -m <s2s spec>
[task]
name = {json.dumps(f"tau-voice/{name}")}
description = {json.dumps(f"tau-voice {domain} task {task_id}: a phone call")}

[metadata]
benchmark = "tau-voice"
domain = {json.dumps(domain)}
task_id = {json.dumps(task_id)}
source = "tau2-bench@2174a60"

[agent]
timeout_sec = 3600

[verifier]
timeout_sec = 900

[environment]
{main_image}build_timeout_sec = 1800
{RESOURCES}
env = {task_env()}
"""


def instruction_md(domain: str, task_id: str, spec: str) -> str:
    """What harbor hands the agent: the call spec, for the call runner.

    Harbor gives an agent the instruction and nothing else of the task
    folder; ``VoiceCallAgent`` reads the ``toml`` block.
    """
    return f"""\
# tau-voice {domain} task {task_id}

A customer-service phone call: a simulated caller (tau2's user simulator,
voiced) calls the agent under test, which answers by voice and uses the
domain's tools. Graded by tau2's evaluator.

This task is run by harbor-voice's call runner
(`harbor_voice.harbor_agent:VoiceCallAgent`), which reads the spec below.

```toml
{spec.rstrip()}
```
"""


def load_task_ids(tau2_root: Path, domain: str, split: str) -> list[str]:
    if split == "parity":
        if not PARITY_TASKS.exists():
            raise SystemExit(
                f"no parity subset yet; {PARITY_TASKS.name} is written when it is chosen"
            )
        return list(
            json.loads(PARITY_TASKS.read_text(encoding="utf-8")).get(domain, [])
        )
    splits = tau2_root / "data" / "tau2" / "domains" / domain / "split_tasks.json"
    return list(json.loads(splits.read_text(encoding="utf-8"))[split])


def write_task(
    out: Path,
    domain: str,
    task_id: str,
    *,
    complexity: str,
    seed: int,
    prebuilt: bool = False,
) -> Path:
    task = out / task_dir_name(domain, task_id)
    (task / "environment").mkdir(parents=True, exist_ok=True)
    (task / "tests").mkdir(exist_ok=True)

    def write(path: Path, text: str) -> None:
        path.write_text(text, encoding="utf-8", newline="\n")

    spec = voice_toml(
        domain, task_id, complexity=complexity, seed=seed, prebuilt=prebuilt
    )
    write(task / "voice.toml", spec)
    write(
        task / "task.toml",
        task_toml(task.name, domain, task_id, prebuilt=prebuilt),
    )
    write(task / "instruction.md", instruction_md(domain, task_id, spec))
    write(task / "environment" / "Dockerfile", images.MAIN_DOCKERFILE)
    # Built: the image is still named, so every task's build lands on one tag.
    source = f"    image: {images.tau2_image()}"
    if not prebuilt:
        source = "    build: ./sidecar\n" + source
        sidecar = task / "environment" / "sidecar"
        sidecar.mkdir(exist_ok=True)
        for name in images.SIDECAR_FILES:
            shutil.copy2(images.SIDECAR / name, sidecar / name)
    env = "\n".join(f"      - {name}" for name in SIDECAR_ENV)
    write(
        task / "environment" / "docker-compose.yaml",
        COMPOSE.format(env=env, review=REVIEW_MODEL, tau2_source=source),
    )
    # Written, not copied: it runs under bash in a Linux container, so it must
    # be LF even when this checkout is CRLF (Windows).
    write(
        task / "tests" / "test.sh",
        (TEMPLATE / "tests" / "test.sh").read_text(encoding="utf-8"),
    )
    return task


def _first_line(doc: str | None) -> str:
    return doc.strip().splitlines()[0] if doc else ""


def build_image(argv: list[str]) -> None:
    parser = argparse.ArgumentParser(
        prog="tau-voice build-image", description=_first_line(images.__doc__)
    )
    parser.add_argument("--force", action="store_true", help="rebuild both")
    args = parser.parse_args(argv)
    for tag in images.build(force=args.force):
        print(tag)


def write_job_config(argv: list[str]) -> None:
    import yaml

    from tau_voice import job

    parser = argparse.ArgumentParser(
        prog="tau-voice job-config", description=_first_line(job.__doc__)
    )
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--model", required=True, help="the S2S agent under test")
    parser.add_argument("--trials", type=int, default=1, help="tau2's --num-trials")
    parser.add_argument("-n", "--concurrent", type=int, default=1)
    parser.add_argument("--run-seed", type=int, default=TAU2_RUN_SEED)
    parser.add_argument("--job-name")
    parser.add_argument(
        "--env", help="harbor backend: docker, daytona, ec2, ... (default docker)"
    )
    parser.add_argument("--task-names", nargs="+", help="only these task folders")
    parser.add_argument("-o", "--out", type=Path, required=True)
    args = parser.parse_args(argv)
    config = job.job_config(
        dataset=args.dataset,
        model=args.model,
        trials=args.trials,
        concurrent=args.concurrent,
        run_seed=args.run_seed,
        job_name=args.job_name,
        environment=args.env,
        task_names=args.task_names,
    )
    args.out.write_text(yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    print(args.out)


def main(argv: list[str] | None = None) -> None:
    import sys

    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["build-image"]:
        build_image(argv[1:])
        return
    if argv[:1] == ["job-config"]:
        write_job_config(argv[1:])
        return
    parser = argparse.ArgumentParser(description=_first_line(__doc__))
    parser.add_argument("--tau2-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--domains", nargs="+", default=list(DOMAINS), choices=DOMAINS)
    parser.add_argument("--split", default="base", help="tau2 split, or 'parity'")
    parser.add_argument("--task-ids", nargs="+", help="only these ids (one domain)")
    parser.add_argument("--limit", type=int, help="first N per domain")
    parser.add_argument(
        "--complexity", default="control", choices=("control", "regular")
    )
    parser.add_argument(
        "--run-seed",
        type=int,
        default=TAU2_RUN_SEED,
        help="tau2's --seed; tasks get its trial-0 seed (a job runner sets later trials)",
    )
    parser.add_argument(
        "--prebuilt",
        action="store_true",
        help="name the images from `tau-voice build-image` instead of building them",
    )
    args = parser.parse_args(argv)

    seed = trial_seeds(args.run_seed, 1)[0]
    written = 0
    for domain in args.domains:
        ids = args.task_ids or load_task_ids(args.tau2_root, domain, args.split)
        if args.limit:
            ids = ids[: args.limit]
        for task_id in ids:
            write_task(
                args.output_dir,
                domain,
                task_id,
                complexity=args.complexity,
                seed=seed,
                prebuilt=args.prebuilt,
            )
            written += 1
    print(f"wrote {written} task(s) to {args.output_dir}")


if __name__ == "__main__":
    main()
