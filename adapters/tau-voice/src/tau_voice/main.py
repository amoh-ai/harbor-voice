"""tau-voice converter: tau2 voice tasks -> harbor-voice task directories.

Run once, locally::

    tau-voice --tau2-root ../tau2-bench --output-dir datasets/tau-voice

Each task directory is a harbor task; harbor's environment layer runs it::

    <domain>-<slug>-<hash>/
    ├── task.toml                   harbor's task config, for harbor's runner
    ├── instruction.md              carries voice.toml for the call runner
    ├── voice.toml                  [call] driver, [environment], [verifier]
    ├── environment/
    │   ├── Dockerfile              main: where harbor-voice runs the call
    │   ├── docker-compose.yaml     adds the tau2 service next to main
    │   └── sidecar/                tau2's image: server, evaluator
    └── tests/test.sh               the verifier, in main; grades via tau2

Run one with ``harbor-voice trials start -p <task> -m <s2s spec>``, or a
dataset with ``harbor-voice jobs start`` (``job-config`` writes the config).

By default both images are built from the task, as harbor tasks are (tau3-bench
builds its runtime the same way) — each trial's ``compose build`` is a cache
hit after the first. ``--prebuilt`` instead names images made once by
``tau-voice build-image`` (:mod:`tau_voice.images`), so a trial makes no
registry or PyPI call before its call starts — frontier-cs's pattern, for
flaky networks and for runs that must not rebuild.

The agent under test is not in the task: the run picks it, as a harbor job
does (``-m openai.realtime/gpt-realtime-1.5``).

Task ids are read from tau2's own ``split_tasks.json`` (``base`` is the split
tau-voice evaluates: airline 50, retail 114, telecom 114), so tau2 need not be
importable here.
"""

from __future__ import annotations

import argparse
import random
import hashlib
import json
import re
import shutil
from pathlib import Path

from tau_voice import images

