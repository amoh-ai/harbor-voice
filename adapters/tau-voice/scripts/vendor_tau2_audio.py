HEADER = """\
# Vendored from tau2-bench @ {commit}: src/tau2/{path}
# MIT License, Copyright (c) 2025 Sierra Research (see LICENSE in this folder).
# Generated by adapters/tau-voice/scripts/vendor_tau2_audio.py: do not edit;
# only import lines differ from the original.
"""


def rewrite(source: str) -> str:
    source = source.replace(
        "from loguru import logger", "from tau_voice.tau2_audio._shim import logger"
    )
    # pyaudio is only for local playback helpers, never on the effects path.
    source = re.sub(
        r"^import pyaudio\n",
        "pyaudio = None  # playback is not vendored\n",
        source,
        flags=re.M,
    )

    def module(match: re.Match[str]) -> str:
        name = match.group(1)
        return f"from {MODULES[name]} import" if name in MODULES else match.group(0)

    source = re.sub(r"^from (tau2[\w.]*) import", module, source, flags=re.M)
    leftover = re.findall(r"^(?:from|import) tau2\b.*$", source, flags=re.M)
    if leftover:
        raise SystemExit(f"unmapped tau2 imports: {leftover}")
    return source


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tau2-root", type=Path, required=True)
    args = parser.parse_args()
    head = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=args.tau2_root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    if head != PINNED:
        raise SystemExit(f"tau2 checkout is at {head}, not the pinned {PINNED}")
    OUT.mkdir(parents=True, exist_ok=True)
    for path, name in FILES.items():
        source = (args.tau2_root / "src" / "tau2" / path).read_text(encoding="utf-8")
        text = HEADER.format(commit=PINNED[:10], path=path) + rewrite(source)
        (OUT / f"{name}.py").write_text(text, encoding="utf-8", newline="\n")
        print(f"vendored {path} -> tau2_audio/{name}.py")


if __name__ == "__main__":
    main()
